LANG_NAMES = {
    "en": "英语",
    "ja": "日语",
    "ko": "韩语",
    "fr": "法语",
    "de": "德语",
    "es": "西班牙语",
    "ru": "俄语",
    "pt": "葡萄牙语",
    "it": "意大利语",
    "ar": "阿拉伯语",
    "th": "泰语",
    "vi": "越南语",
}


def get_language_name(lang_code: str) -> str:
    """Get Chinese display name for a language code."""
    return LANG_NAMES.get(lang_code, f"{lang_code}语")
